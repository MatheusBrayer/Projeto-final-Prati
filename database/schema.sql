CREATE TABLE movimentacoes_estoque (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peca_id INTEGER NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    quantidade INTEGER NOT NULL,
    valor_unitario NUMERIC(10,2),
    ordem_servico_id INTEGER,
    ordem_servico_peca_id INTEGER,
    fornecedor_id INTEGER,
    compra_id INTEGER,
    observacao VARCHAR(255),
    data_movimentacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    os_peca_saida_unica INTEGER GENERATED ALWAYS AS (CASE WHEN tipo = 'SAIDA' THEN ordem_servico_peca_id ELSE NULL END) STORED,
    CONSTRAINT uk_mov_estoque_compra_peca_tipo UNIQUE (compra_id, peca_id, tipo),
    CONSTRAINT uk_mov_estoque_os_peca_saida UNIQUE (os_peca_saida_unica),
    CONSTRAINT fk_movimentacao_compra FOREIGN KEY (compra_id) REFERENCES compras(id),
    CONSTRAINT fk_movimentacao_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES fornecedores(id),
    CONSTRAINT fk_movimentacao_ordem FOREIGN KEY (ordem_servico_id) REFERENCES ordens_servico(id),
    CONSTRAINT fk_movimentacao_os_peca FOREIGN KEY (ordem_servico_peca_id) REFERENCES ordem_servico_pecas(id),
    CONSTRAINT fk_movimentacao_peca FOREIGN KEY (peca_id) REFERENCES pecas(id),
    CONSTRAINT chk_movimentacoes_quantidade CHECK (quantidade > 0),
    CONSTRAINT chk_movimentacoes_valor_unitario CHECK (valor_unitario IS NULL OR valor_unitario >= 0),
    CONSTRAINT chk_movimentacoes_tipo CHECK (tipo IN ('ENTRADA','SAIDA','AJUSTE_ENTRADA','AJUSTE_SAIDA'))
);
CREATE INDEX idx_movimentacao_peca ON movimentacoes_estoque(peca_id);
CREATE INDEX idx_movimentacao_ordem ON movimentacoes_estoque(ordem_servico_id);
CREATE INDEX idx_movimentacao_fornecedor ON movimentacoes_estoque(fornecedor_id);
CREATE INDEX idx_movimentacao_os_peca ON movimentacoes_estoque(ordem_servico_peca_id);

CREATE TABLE contas_pagar (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id INTEGER,
    despesa_id INTEGER,
    diaria_funcionario_id INTEGER,
    fornecedor_id INTEGER,
    descricao VARCHAR(150) NOT NULL,
    valor_total NUMERIC(10,2) NOT NULL,
    data_emissao DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    observacao VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_contas_pagar_diaria UNIQUE (diaria_funcionario_id),
    CONSTRAINT uk_contas_pagar_compra UNIQUE (compra_id),
    CONSTRAINT uk_contas_pagar_despesa UNIQUE (despesa_id),
    CONSTRAINT fk_contas_pagar_compra FOREIGN KEY (compra_id) REFERENCES compras(id),
    CONSTRAINT fk_contas_pagar_despesa FOREIGN KEY (despesa_id) REFERENCES despesas(id),
    CONSTRAINT fk_contas_pagar_diaria FOREIGN KEY (diaria_funcionario_id) REFERENCES diarias_funcionarios(id),
    CONSTRAINT fk_contas_pagar_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES fornecedores(id),
    CONSTRAINT chk_contas_pagar_valor_total CHECK (valor_total >= 0),
    CONSTRAINT chk_contas_pagar_status CHECK (status IN ('PENDENTE','PARCIAL','PAGO','CANCELADO')),
    CONSTRAINT chk_contas_pagar_origem CHECK ((CASE WHEN compra_id IS NOT NULL THEN 1 ELSE 0 END) + (CASE WHEN despesa_id IS NOT NULL THEN 1 ELSE 0 END) + (CASE WHEN diaria_funcionario_id IS NOT NULL THEN 1 ELSE 0 END) <= 1)
);
CREATE INDEX idx_contas_pagar_fornecedor ON contas_pagar(fornecedor_id);

