
CREATE TABLE clientes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cpf_cnpj VARCHAR(20),
    telefone VARCHAR(20) NOT NULL,
    email VARCHAR(150),
    cep VARCHAR(10),
    rua VARCHAR(150),
    numero VARCHAR(20),
    bairro VARCHAR(100),
    cidade VARCHAR(100),
    estado CHAR(2),
    ativo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_clientes_cpf_cnpj UNIQUE (cpf_cnpj),
    CONSTRAINT chk_clientes_ativo CHECK (ativo IN (0,1)),
    CONSTRAINT chk_clientes_estado CHECK (estado IS NULL OR UPPER(estado) IN ('AC','AL','AP','AM','BA','CE','DF','ES','GO','MA','MT','MS','MG','PA','PB','PR','PE','PI','RJ','RN','RS','RO','RR','SC','SP','SE','TO'))
);

CREATE TABLE funcionarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    telefone VARCHAR(20),
    email VARCHAR(150),
    cargo VARCHAR(50) NOT NULL,
    data_admissao DATE,
    salario NUMERIC(10,2),
    percentual_comissao NUMERIC(5,2),
    ativo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_vinculo VARCHAR(20) NOT NULL DEFAULT 'FIXO',
    valor_diaria NUMERIC(10,2),
    CONSTRAINT chk_funcionarios_salario CHECK (salario IS NULL OR salario >= 0),
    CONSTRAINT chk_funcionarios_comissao CHECK (percentual_comissao IS NULL OR percentual_comissao BETWEEN 0 AND 100),
    CONSTRAINT chk_funcionarios_valor_diaria CHECK (valor_diaria IS NULL OR valor_diaria >= 0),
    CONSTRAINT chk_funcionarios_tipo_vinculo CHECK (tipo_vinculo IN ('FIXO','FREELANCE')),
    CONSTRAINT chk_funcionarios_vinculo_valores CHECK ((tipo_vinculo = 'FIXO' AND valor_diaria IS NULL) OR (tipo_vinculo = 'FREELANCE' AND salario IS NULL)),
    CONSTRAINT chk_funcionarios_ativo CHECK (ativo IN (0,1))
);

