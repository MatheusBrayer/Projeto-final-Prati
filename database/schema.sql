CREATE TABLE ordens_servico (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    veiculo_id INTEGER NOT NULL,
    data_abertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_fechamento TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'ABERTA',
    problema_relatado TEXT,
    observacoes TEXT,
    valor_servicos NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    valor_pecas NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ordens_servico_veiculo FOREIGN KEY (veiculo_id) REFERENCES veiculos(id),
    CONSTRAINT chk_ordens_valor_servicos CHECK (valor_servicos >= 0),
    CONSTRAINT chk_ordens_valor_pecas CHECK (valor_pecas >= 0),
    CONSTRAINT chk_ordens_status CHECK (status IN ('ABERTA','EM_ANDAMENTO','FINALIZADA','CANCELADA')),
    CONSTRAINT chk_ordens_datas CHECK (data_fechamento IS NULL OR data_fechamento >= data_abertura),
    CONSTRAINT chk_ordens_status_fechamento CHECK (((status IN ('ABERTA','EM_ANDAMENTO')) AND data_fechamento IS NULL) OR ((status IN ('FINALIZADA','CANCELADA')) AND data_fechamento IS NOT NULL))
);
CREATE INDEX idx_ordens_servico_veiculo ON ordens_servico(veiculo_id);

