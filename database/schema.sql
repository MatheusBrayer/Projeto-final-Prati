CREATE TABLE pecas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    descricao VARCHAR(255),
    marca VARCHAR(80),
    valor_custo NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    valor_venda NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    estoque INTEGER NOT NULL DEFAULT 0,
    estoque_minimo INTEGER NOT NULL DEFAULT 0,
    ativo SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_pecas_estoque CHECK (estoque >= 0),
    CONSTRAINT chk_pecas_valor_custo CHECK (valor_custo >= 0),
    CONSTRAINT chk_pecas_valor_venda CHECK (valor_venda >= 0),
    CONSTRAINT chk_pecas_estoque_minimo CHECK (estoque_minimo >= 0),
    CONSTRAINT chk_pecas_ativo CHECK (ativo IN (0,1))
);

CREATE TABLE servicos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
